// Shared cross-sections keep neighbouring bone textures joined at the knee.
export function ribbon(points, widths) {
  return points.flatMap(([x, y], i) => {
    const before = points[Math.max(0, i - 1)], after = points[Math.min(points.length - 1, i + 1)];
    const dx = after[0] - before[0], dy = after[1] - before[1];
    const radius = widths[i] / (2 * Math.hypot(dx, dy));
    return [[x - dy * radius, y + dx * radius], [x + dy * radius, y - dx * radius]];
  });
}
